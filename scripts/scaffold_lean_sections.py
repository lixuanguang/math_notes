#!/usr/bin/env python3
"""Create Lean section stubs mirroring the LaTeX section tree."""

from __future__ import annotations

import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEX_ROOT = ROOT / "sections"
LEAN_ROOT = ROOT / "MathNotes"
ROOT_MODULE = ROOT / "MathNotes.lean"


def lean_component(name: str) -> str:
    """Return a Lean import component, escaping non-identifiers."""
    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*", name):
        return name
    return f"«{name}»"


def module_name(path: Path) -> str:
    """Convert a Lean source path to its importable module name."""
    rel = path.relative_to(ROOT).with_suffix("")
    return ".".join(lean_component(part) for part in rel.parts)


def title_from_stem(stem: str) -> str:
    words = stem.replace("_", " ").split()
    return " ".join(word.capitalize() for word in words)


def stub_content(tex_path: Path, lean_path: Path) -> str:
    tex_rel = tex_path.relative_to(ROOT)
    title = title_from_stem(tex_path.stem)
    if tex_path == TEX_ROOT / "base.tex":
        import_line = "import Mathlib"
    else:
        import_line = "import MathNotes.sections.base"

    return f"""{import_line}

/-!
# {title}

Lean counterpart of `{tex_rel}`.
-/

namespace MathNotes

end MathNotes
"""


def main() -> None:
    tex_files = sorted(TEX_ROOT.rglob("*.tex"))
    lean_files: list[Path] = []

    for tex_path in tex_files:
        rel = tex_path.relative_to(TEX_ROOT).with_suffix(".lean")
        lean_path = LEAN_ROOT / "sections" / rel
        lean_files.append(lean_path)
        if lean_path.exists():
            continue
        lean_path.parent.mkdir(parents=True, exist_ok=True)
        lean_path.write_text(stub_content(tex_path, lean_path), encoding="utf-8")

    imports = "\n".join(f"import {module_name(path)}" for path in lean_files)
    ROOT_MODULE.write_text(
        f"""{imports}

/-!
# Math Notes

Root module importing Lean counterparts of the LaTeX section tree.

This file is generated by `scripts/scaffold_lean_sections.py`.
-/
""",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
